/// The engine lowercase of `cp` under a locale-library identifier alphabet.
pub fn lower(cp: u32) -> u32 {
    RUNS.iter()
        .find(|&&(first, last, stride, _)| {
            (first..=last).contains(&cp) && (cp - first).is_multiple_of(stride)
        })
        .map_or(cp, |&(_, _, _, delta)| cp.wrapping_add_signed(delta))
}
