#!/usr/bin/env bash
# Long run of the operations scenario (T39 workspace#594): every path of paths.tsv on both sides (migrated, official),
# all four sides at once on their own install copies and ports, each through side_loop.sh; a summary file refreshed
# every minute while they run; parity of the two sides of each path at the end. Interface: e2e/ops/longrun/README.md.
#
# Input: bash e2e/ops/longrun/run.sh <bin> <out dir>
# env: FASTMIG_LONGRUN_INSTALL (the optdebug develop install; copied per side, never written), FASTMIG_LONGRUN_PORTS
#   (four claimed ports, in the order of paths.tsv rows x migrated, official), FASTMIG_OPS_SERVER_CTL (required);
#   FASTMIG_LONGRUN_BASEDB_ROOT (~/fastmig-basedb), FASTMIG_LONGRUN_CAP_GB (50), FASTMIG_LONGRUN_GROWTH_MB (MB a DML
#   round adds to a side, for the size estimate; README § Disk), FASTMIG_LONGRUN_PATHS (ids of paths.tsv, default all),
#   and side_loop.sh's FASTMIG_LONGRUN_* settings, passed through.
# Output: <out>/<path>/<side>/ (side_loop.sh's side out dir), <out>/<path>/<side>.console, <out>/<path>/parity/ and
#   parity.tsv, <out>/summary.md (refreshed every minute),
#   <out>/sides.tsv, <out>/meta.txt, <out>/result (first line "RESULT: OK" or "RESULT: FAILED", written last).
#   Exit 0 pass, 1 fail, 2 bad arguments or the disk gate. Removes nothing: <out> holds the install copies and backup
#   chains until the caller removes them by literal path (README § Disk).
set -uo pipefail

BIN=$(realpath "${1:?cubrid-fastmig binary}")
OUT=${2:?out dir}
BASE_INST=$(realpath "${FASTMIG_LONGRUN_INSTALL:?FASTMIG_LONGRUN_INSTALL required}")
read -r -a PORTS <<<"${FASTMIG_LONGRUN_PORTS:?FASTMIG_LONGRUN_PORTS required (four ports)}"
: "${FASTMIG_OPS_SERVER_CTL:?FASTMIG_OPS_SERVER_CTL required}"
ROOT=$(realpath "${FASTMIG_LONGRUN_BASEDB_ROOT:-$HOME/fastmig-basedb}")
CAP_GB=${FASTMIG_LONGRUN_CAP_GB:-50}
GROWTH_MB=${FASTMIG_LONGRUN_GROWTH_MB:-2}
HERE=$(dirname "$(realpath "$0")")

[ ! -e "$OUT" ] || { echo "$OUT exists" >&2; exit 2; }
[ -x "$BIN" ] || { echo "no binary $BIN (just release)" >&2; exit 2; }
rel=$(CUBRID=$BASE_INST LD_LIBRARY_PATH=$BASE_INST/lib "$BASE_INST/bin/cubrid_rel" 2>&1 | grep -m1 'CUBRID')
case "$rel" in *"release build"* | *"CUBRID 11.4."*) echo "install is not an optdebug develop build: $rel" >&2; exit 2 ;; esac
mapfile -t ROWS < <(awk -F'\t' -v want="${FASTMIG_LONGRUN_PATHS:-}" 'NR > 1 && (want == "" || index(" " want " ", " " $1 " "))' "$HERE/paths.tsv")
(( ${#ROWS[@]} > 0 )) || { echo "no path selected" >&2; exit 2; }
(( ${#PORTS[@]} == 2 * ${#ROWS[@]} )) || { echo "need $(( 2 * ${#ROWS[@]} )) ports, got ${#PORTS[@]}" >&2; exit 2; }

# disk gate (README § Disk): per side the pristine, its growth, the archives log_max_archives keeps plus the active log
# and two spare, every chain at twice the grown DB, and the one restored DB at a time of the end; all sides together under the
# cap, and twice that free on /home
cycles=${FASTMIG_LONGRUN_CYCLES:-8} rounds=${FASTMIG_LONGRUN_ROUNDS:-30} every=${FASTMIG_LONGRUN_KILL_EVERY:-4}
kept=${FASTMIG_LONGRUN_MAX_ARCHIVES:-40}
est=0
for r in "${ROWS[@]}"; do
  IFS=$'\t' read -r id pr tv <<<"$r"
  p=$(du -smL "$ROOT/$pr" | cut -f1)
  lg=$(( $(stat -c %s "$(ls "$ROOT/$pr"/*_lgat | head -1)") / 1048576 ))
  grown=$(( p + cycles * rounds * GROWTH_MB ))
  est=$(( est + 2 * (grown + (kept + 3) * lg + (cycles / every + 1) * 2 * grown + grown) ))
done
avail=$(df -m --output=avail /home | tail -1 | tr -d ' ')
echo "size estimate ${est} MB for ${#ROWS[@]} paths x 2 sides; cap $(( CAP_GB * 1024 )) MB; /home avail ${avail} MB"
(( est <= CAP_GB * 1024 )) || { echo "estimate over the cap" >&2; exit 2; }
(( avail >= 2 * est )) || { echo "/home has less than twice the estimate free" >&2; exit 2; }

mkdir -p "$OUT/installs"
OUT=$(realpath "$OUT")
{ echo "bin_sha256=$(sha256sum "$BIN" | cut -d' ' -f1) install=$BASE_INST"
  echo "$rel"
  echo "libcubrid_sha256=$(sha256sum "$BASE_INST/lib/libcubrid.so" | cut -d' ' -f1)"
  echo "paths=$(printf '%s ' "${ROWS[@]%%$'\t'*}")ports=${PORTS[*]} estimate_mb=$est"
  env | grep '^FASTMIG_LONGRUN_' | sort
  echo "pre: $(date -Is) load=$(cut -d' ' -f1-3 /proc/loadavg) home_avail_mb=$avail"
} >"$OUT/meta.txt"

# cleanup_script <path id> <side>: writes <out>/cleanup/<path>-<side>.sh, one case per restore probe (and the PITR lob
# copy) with its rm -rf path spelled out literally (house rule: rm -rf takes literal paths only; the generator fixes them
# in a file before the run, as the T29 measurement drivers do). side_loop.sh runs one case as soon as that probe's
# checks are done, so the restored DBs never pile up.
cleanup_script() {
  local d=$OUT/$1/$2/$2 f=$OUT/cleanup/$1-$2.sh p
  { echo "#!/usr/bin/env bash"
    echo "# generated by e2e/ops/longrun/run.sh for $1 $2: bash $f <probe|pitr-lob>"
    echo "case \"\$1\" in"
    for p in latest pitr chain0-bktime before-move chain0-next; do echo "  $p) rm -rf $d/restore/$p ;;"; done
    echo "  pitr-lob) rm -rf $d/pitr-lob ;;"
    echo "  *) echo \"unknown probe \$1\" >&2; exit 2 ;;"
    echo "esac"
  } >"$f"
}
mkdir -p "$OUT/cleanup"

# every install copy first: a failed copy then leaves no side running
for r in "${ROWS[@]}"; do
  id=${r%%$'\t'*}
  mkdir -p "$OUT/$id"
  for s in migrated official; do
    cp -a --reflink=always "$BASE_INST" "$OUT/installs/$id-$s" || { echo "install copy failed" >&2; exit 1; }
    cleanup_script "$id" "$s"
  done
done

# stop_run: on TERM or INT (a watcher's deadline, a Ctrl-C) the side processes stop first, with their csql and
# restoredb children when run.sh leads its process group (setsid, as the worker starts it), then every cub_server,
# cub_master and cub_pl of this run's installs (CUBRID=<out>/installs/ in their environment, as sides.sh stop_master
# matches): a side left alone would go on to its end and start restored DBs on ports the watcher already released.
stop_run() {
  trap '' TERM INT
  if [ "$(ps -o pgid= $$ | tr -d ' ')" = "$$" ]; then kill -TERM -- -$$; else kill -TERM "${PIDS[@]}"; fi 2>/dev/null
  local p i
  for ((i = 0; i < 30; i++)); do
    for p in "${PIDS[@]}"; do kill -0 "$p" 2>/dev/null && break; done || break
    sleep 1
  done
  for p in $(pgrep -x cub_server) $(pgrep -x cub_master) $(pgrep -x cub_pl); do
    tr '\0' '\n' <"/proc/$p/environ" 2>/dev/null | grep -q "^CUBRID=$OUT/installs/" && { echo "SIGTERM $p $(cat /proc/$p/comm)"; kill -TERM "$p"; }
  done >>"$OUT/stop.log" 2>&1
  echo "RESULT: FAILED (stopped by a signal at $(date -Is); see stop.log)" >"$OUT/result"
  exit 1
}
PIDS=()
trap stop_run TERM INT

printf 'path\tside\tport\tpid\trc\n' >"$OUT/sides.tsv.run"
i=0
for r in "${ROWS[@]}"; do
  IFS=$'\t' read -r id pr tv <<<"$r"
  for s in migrated official; do
    FASTMIG_OPS_INSTALL=$OUT/installs/$id-$s FASTMIG_OPS_PORT=${PORTS[$i]} FASTMIG_LONGRUN_CLEANUP=$OUT/cleanup/$id-$s.sh \
      bash "$HERE/side_loop.sh" "$BIN" "$ROOT/$pr" "$tv" "$OUT/$id/$s" "$s" >"$OUT/$id/$s.console" 2>&1 &
    PIDS+=($!)
    printf '%s\t%s\t%s\t%s\n' "$id" "$s" "${PORTS[$i]}" "$!" >>"$OUT/sides.tsv.run"
    i=$(( i + 1 ))
  done
done

# the summary a watcher reads while the run lasts; its mtime is the liveness signal (README § Watching)
while :; do
  bash "$HERE/summarize.sh" "$OUT" >"$OUT/summary.md.new" 2>&1 && mv "$OUT/summary.md.new" "$OUT/summary.md"
  alive=0; for p in "${PIDS[@]}"; do kill -0 "$p" 2>/dev/null && alive=1; done
  [ "$alive" = 1 ] || break
  sleep 60
done

FAIL=0
printf 'path\tside\tport\tpid\trc\n' >"$OUT/sides.tsv"
while IFS=$'\t' read -r id s port pid; do
  wait "$pid"; rc=$?
  printf '%s\t%s\t%s\t%s\t%s\n' "$id" "$s" "$port" "$pid" "$rc" >>"$OUT/sides.tsv"
  [ "$rc" = 0 ] || FAIL=1
done < <(tail -n +2 "$OUT/sides.tsv.run")

# parity: every check the migrated side wrote against the official side's of the same name
for r in "${ROWS[@]}"; do
  id=${r%%$'\t'*}
  mkdir -p "$OUT/$id/parity"; printf 'check\tdiff_rc\n' >"$OUT/$id/parity.tsv"
  for f in "$OUT/$id"/migrated/migrated/check/*.out; do
    n=$(basename "$f" .out)
    diff "$f" "$OUT/$id/official/official/check/$n.out" >"$OUT/$id/parity/$n.diff" 2>&1
    rc=$?
    printf '%s\t%s\n' "$n" "$rc" >>"$OUT/$id/parity.tsv"
    [ "$rc" = 0 ] || { FAIL=1; echo "$id parity $n: differs" >&2; }
  done
  [ -n "$(ls "$OUT/$id"/migrated/migrated/check/*.out 2>/dev/null)" ] || FAIL=1
done

bash "$HERE/summarize.sh" "$OUT" >"$OUT/summary.md" 2>&1
echo "post: $(date -Is) load=$(cut -d' ' -f1-3 /proc/loadavg) out_mb=$(du -sm "$OUT" | cut -f1) fail=$FAIL" >>"$OUT/meta.txt"
if [ "$FAIL" = 0 ]; then echo "RESULT: OK" >"$OUT/result"; else echo "RESULT: FAILED" >"$OUT/result"; fi
echo "left on disk (remove by literal path once read): $OUT"
exit $FAIL
