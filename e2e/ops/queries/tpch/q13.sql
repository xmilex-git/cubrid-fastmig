-- TPC-H Query 13: Customer Distribution
-- T40 (workspace#595): as TPC-H/scale10/queries/q13.sql (its ORDER BY is total, or one row)
select
	c_count,
	count(*) as custdist
from
	(
		select
			c_custkey,
			count(o_orderkey) as c_count
		from
			customer left outer join orders on
				c_custkey = o_custkey
				and o_comment not like '%special%requests%'
		group by
			c_custkey
	) as c_orders
group by
	c_count
order by
	custdist desc,
	c_count desc;
