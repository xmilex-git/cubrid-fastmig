#!/usr/bin/env bash
# Writes meas_round1.sh: the reduced matrix of 1번 세션 (2026-10-30), 2 cold reps, every target removed by literal path.
#   per device (nvme, ssd, hdd) and path (A, B): fm W1, fm W16, fm_copy W16; per device: cp_a and cp_reflink of B;
#   nvme2hdd: A fm W16.
. "$(dirname "$0")/env.sh"
out=$S/scripts/meas_round1.sh
{
  echo '#!/usr/bin/env bash'
  echo "# generated by gen_meas.sh"
  echo "S=$S"
  for rep in 1 2; do
    for dev in nvme ssd hdd; do
      t=$(devdir $dev)/meas
      for cfg in "A fm 1" "A fm 16" "A fm_copy 16" "B fm 1" "B fm 16" "B fm_copy 16" "B cp_a 16" "B cp_reflink 16"; do
        set -- $cfg
        echo "bash \$S/scripts/run_one.sh $dev $1 $2 $3 $rep || echo \"FAILED $dev $1 $2 w$3 r$rep\""
        echo "rm -rf $t/$dev-$1-$2-w$3-r$rep"
      done
    done
    echo "bash \$S/scripts/run_one.sh nvme2hdd A fm 16 $rep || echo \"FAILED nvme2hdd A fm w16 r$rep\""
    echo "rm -rf $(devdir hdd)/meas/nvme2hdd-A-fm-w16-r$rep"
  done
  echo 'echo "MEAS_ROUND1 DONE"'
} > $out
echo "wrote $out ($(wc -l < $out) lines)"
